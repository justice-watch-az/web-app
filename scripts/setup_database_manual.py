def load_credentials() -> Dict[str, str]:
    """Load Supabase credentials from .env.github"""
    env_file = '.env.github'
    if not os.path.exists(env_file):
        raise FileNotFoundError(f"{env_file} not found!")
    
    load_dotenv(env_file)
    
    credentials = {
        'url': os.getenv('SUPABASE_URL'),
        'anon_key': os.getenv('SUPABASE_ANON_KEY'),
        'service_key': os.getenv('SUPABASE_SERVICE_KEY'),
    }
    
    missing = [k for k, v in credentials.items() if not v]
    if missing:
        raise ValueError(f"Missing credentials: {', '.join(missing)}")
    
    return credentials

def generate_combined_sql() -> str:
    """Combine all SQL files into one script"""
    sql_files = [
        "supabase/migrations/20250117_justice_watch_schema.sql",
        "supabase/migrations/001_cron_scheduler.sql"
    ]
    
    combined_sql = """-- Justice Watch Production Database Setup
-- Generated by setup_database_manual.py
-- Execute this in Supabase SQL Editor

"""
    
    for sql_file in sql_files:
        if os.path.exists(sql_file):
            combined_sql += f"\n-- ========================================\n"
            combined_sql += f"-- {sql_file}\n"
            combined_sql += f"-- ========================================\n\n"
            
            with open(sql_file, 'r') as f:
                combined_sql += f.read()
            
            combined_sql += "\n\n"
        else:
            print(f"⚠️  Warning: {sql_file} not found")
    
    return combined_sql

def create_verification_sql() -> str:
    """Create SQL for verifying the setup"""
    return """-- Verification Queries
-- Run these to verify your database setup

-- 1. Check all tables exist
SELECT table_name 
FROM information_schema.tables 
WHERE table_schema = 'public' 
AND table_name IN ('cases', 'case_parties', 'case_charges', 'case_calendar', 'cron_schedules', 'cron_executions')
ORDER BY table_name;

-- 2. Check RLS is enabled
SELECT tablename, rowsecurity 
FROM pg_tables 
WHERE schemaname = 'public' 
AND tablename IN ('cases', 'case_parties', 'case_charges', 'case_calendar')
ORDER BY tablename;

-- 3. Test database functions
SELECT get_case_stats();

-- 4. Check indexes exist
SELECT indexname, tablename 
FROM pg_indexes 
WHERE schemaname = 'public' 
AND tablename IN ('cases', 'case_parties', 'case_charges', 'case_calendar')
ORDER BY tablename, indexname;

-- 5. Verify policies exist
SELECT policyname, tablename, cmd, roles 
FROM pg_policies 
WHERE schemaname = 'public'
ORDER BY tablename, policyname;
"""

def test_connection(credentials: Dict[str, str]) -> bool:
    """Test connection to Supabase"""
    try:
        # Test with anonymous key
        anon_client = create_client(credentials['url'], credentials['anon_key'])
        # Simple connection test - this will work even with empty database
        print("✅ Anonymous client connection successful")
        
        # Test with service key  
        service_client = create_client(credentials['url'], credentials['service_key'])
        print("✅ Service role client connection successful")
        
        return True
    except Exception as e:
        print(f"❌ Connection test failed: {e}")
        return False

